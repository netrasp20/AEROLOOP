"""Read-only bootloader transport abstraction.

The identity reader consumes :class:`BootloaderTransport`. No part of the
compatibility resolver imports this module, so serial/USB details can never
leak into firmware-selection policy.

Why an abstraction and not a pyserial client
-------------------------------------------
The physical bootloader client is intentionally **not implemented in this
phase**. Reaching it requires rebooting the board into bootloader mode, which is
explicitly out of scope. What is implemented here is the seam, so that the
future client is a drop-in replacement with no change to the reader or the
resolver.

Read-only contract
------------------
The protocol surface exposed by this module is deliberately minimal and
contains no mutation capability:

* :meth:`BootloaderTransport.connect`  — open the already-open bootloader port
* :meth:`BootloaderTransport.read_info` — read identity signals
* :meth:`BootloaderTransport.disconnect` — close it

There is deliberately **no** ``erase``, ``program``, ``write``, ``reboot`` or
``reboot_to_bootloader`` method on this interface. Any future implementation
that needs those belongs in a separate, separately-gated module, so that
"can read identity" and "can modify a board" can never be confused.

Safety
------
Nothing here knows about ``/dev/ttyACM0`` or any other concrete device. The
real Pixhawk is never opened by this module, and no default port is supplied:
a transport must be constructed with an explicit port by an explicit caller.
"""

from __future__ import annotations

import abc
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from services.bootloader_identity import SOURCE_BOOTLOADER, unavailable_identity


class BootloaderTransportError(RuntimeError):
    """Raised when the bootloader transport cannot be used."""


@dataclass
class RawBootloaderInfo:
    """Unvalidated values as received from a bootloader device.

    All fields are optional and untyped-by-contract: this is the transport's
    honest output. Validation belongs to
    :mod:`services.bootloader_identity.build_identity`, so a transport can
    never smuggle an unchecked value into firmware resolution.
    """

    bootloader_revision: Any = None
    board_id: Any = None
    flash_size: Any = None
    usb_product_string: Any = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "bootloaderRevision": self.bootloader_revision,
            "boardId": self.board_id,
            "flashSize": self.flash_size,
            "usbProductString": self.usb_product_string,
        }


@dataclass
class BootloaderPortDescriptor:
    """USB-level description of a port believed to be in bootloader mode.

    In bootloader mode the USB product string is the board's
    ``HAL_USB_STRING_PRODUCT``, generated by ``chibios_hwdef.py`` as
    ``"%BOARD%-BL"``. It is the corroborating signal for the board-id-9
    collision.

    This describes a *candidate* port only. Whether it is actually in
    bootloader mode is not assumed, and this module performs no enumeration of
    real devices.
    """

    system_location: str
    usb_product_string: Optional[str] = None
    manufacturer: Optional[str] = None
    vendor_id: Optional[int] = None
    product_id: Optional[int] = None
    serial_number: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {
            "systemLocation": self.system_location,
            "usbProductString": self.usb_product_string,
            "manufacturer": self.manufacturer,
            "vendorId": self.vendor_id,
            "productId": self.product_id,
            "serialNumber": self.serial_number,
        }


class BootloaderTransport(abc.ABC):
    """Minimal read-only bootloader transport.

    Implementations may be a real serial client (future phase) or the
    synthetic fixture transport used by the tests.
    """

    #: Human-readable description used in evidence strings.
    name: str = "bootloader-transport"

    @abc.abstractmethod
    def connect(self) -> None:
        """Attach to a port that is *already* in bootloader mode.

        Implementations must not reboot the target, request a bootloader
        entry, or otherwise change device state.
        """

    @abc.abstractmethod
    def read_info(self) -> RawBootloaderInfo:
        """Read ``INFO_BL_REV``, ``INFO_BOARD_ID``, ``INFO_FLASH_SIZE``.

        Also returns the USB product string for the port, which the transport
        obtains from USB descriptors rather than the wire protocol.
        """

    @abc.abstractmethod
    def disconnect(self) -> None:
        """Detach without changing device state."""

    # -- convenience, shared by all transports -------------------------------

    def is_connected(self) -> bool:
        return bool(getattr(self, "_connected", False))

    def read_identity(self) -> Any:
        """Convenience: connect, read, disconnect, validate.

        Returns a
        :class:`~services.bootloader_identity.BootloaderIdentityResult`.
        ``disconnect`` runs even when reading fails, so a failed read never
        leaves a port open.
        """
        from services.bootloader_identity import SOURCE_BOOTLOADER, build_identity

        try:
            self.connect()
        except BootloaderTransportError as exc:
            return unavailable_identity(
                f"Could not attach to the bootloader transport: {exc}", SOURCE_BOOTLOADER
            )
        except Exception as exc:  # pragma: no cover - defensive
            return unavailable_identity(
                f"Unexpected bootloader transport failure while attaching: {exc}",
                SOURCE_BOOTLOADER,
            )

        try:
            raw = self.read_info()
        except BootloaderTransportError as exc:
            return unavailable_identity(
                f"Could not read the bootloader identity: {exc}", SOURCE_BOOTLOADER
            )
        except Exception as exc:  # pragma: no cover - defensive
            return unavailable_identity(
                f"Unexpected bootloader transport failure while reading: {exc}",
                SOURCE_BOOTLOADER,
            )
        finally:
            try:
                self.disconnect()
            except Exception:  # pragma: no cover - defensive
                pass

        if raw is None:
            return unavailable_identity(
                "The bootloader transport returned no identity information.",
                SOURCE_BOOTLOADER,
            )

        return build_identity(
            bootloader_revision=raw.bootloader_revision,
            board_id=raw.board_id,
            flash_size=raw.flash_size,
            usb_product_string=raw.usb_product_string,
            source=SOURCE_BOOTLOADER,
        )


class BootloaderIdentityReader:
    """Turns a :class:`BootloaderTransport` into a validated identity.

    This is the only component that knows how to reach a transport. It holds
    no firmware-selection logic, so it can be exercised with the synthetic
    fixture transport without any hardware present.
    """

    def __init__(self, transport: BootloaderTransport) -> None:
        if transport is None:
            raise ValueError("A BootloaderTransport instance is required.")
        self._transport = transport

    @property
    def transport_name(self) -> str:
        return getattr(self._transport, "name", type(self._transport).__name__)

    def read(self) -> Any:
        """Read and validate one identity from the configured transport."""
        result = self._transport.read_identity()
        # Annotate evidence with which transport produced it, so a fixture
        # result can never be mistaken for a hardware reading.
        identity = result.identity
        annotated = BootloaderIdentityLike(
            bootloader_revision=identity.bootloader_revision,
            board_id=identity.board_id,
            flash_size=identity.flash_size,
            usb_product_string=identity.usb_product_string,
            source=identity.source,
            validity=identity.validity,
            errors=list(identity.errors),
        )
        evidence = [f"Identity source: {self.transport_name}"] + list(result.evidence)
        return type(result)(identity=annotated, evidence=evidence)


@dataclass(frozen=True)
class BootloaderIdentityLike:
    """Structural copy used to re-stamp an identity's source/evidence.

    Kept local so the reader does not need to import the concrete identity
    dataclass twice under different names.
    """

    bootloader_revision: Optional[int] = None
    board_id: Optional[int] = None
    flash_size: Optional[int] = None
    usb_product_string: Optional[str] = None
    source: str = SOURCE_BOOTLOADER
    validity: str = "UNAVAILABLE"
    errors: List[str] = field(default_factory=list)

    @property
    def is_valid(self) -> bool:
        return self.validity == "VALID"

    @property
    def is_complete(self) -> bool:
        return (
            self.bootloader_revision is not None
            and self.board_id is not None
            and self.flash_size is not None
            and self.usb_product_string is not None
        )

    @property
    def missing_fields(self) -> List[str]:
        gaps = []
        if self.bootloader_revision is None:
            gaps.append("bootloaderRevision")
        if self.board_id is None:
            gaps.append("boardId")
        if self.flash_size is None:
            gaps.append("flashSize")
        if self.usb_product_string is None:
            gaps.append("usbProductString")
        return gaps

    def to_dict(self) -> Dict[str, Any]:
        return {
            "bootloaderRevision": self.bootloader_revision,
            "boardId": self.board_id,
            "flashSize": self.flash_size,
            "usbProductString": self.usb_product_string,
            "source": self.source,
            "validity": self.validity,
            "errors": list(self.errors),
            "isComplete": self.is_complete,
            "missingFields": self.missing_fields,
        }
